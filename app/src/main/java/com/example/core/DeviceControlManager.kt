package com.example.core

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import android.hardware.camera2.CameraManager
import android.net.Uri
import android.os.Build
import android.provider.Settings
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

enum class SystemPanelType {
    WIFI,
    BLUETOOTH,
    VOLUME,
    DISPLAY,
    ACCESSIBILITY,
    NOTIFICATION_ACCESS,
    APP_SETTINGS
}

class DeviceControlManager(private val context: Context) {

    fun dialNumber(phoneNumber: String): Boolean {
        val clean = phoneNumber.trim()
        if (clean.isEmpty()) return false
        val intent = Intent(Intent.ACTION_DIAL).apply {
            data = Uri.parse("tel:$clean")
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return startSafe(intent)
    }

    fun sendSms(phoneNumber: String, message: String): Boolean {
        val clean = phoneNumber.trim()
        val intent = Intent(Intent.ACTION_SENDTO).apply {
            data = Uri.parse("smsto:$clean")
            putExtra("sms_body", message)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return startSafe(intent)
    }

    fun shareText(title: String, body: String): Boolean {
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, title)
            putExtra(Intent.EXTRA_TEXT, body)
        }
        val chooser = Intent.createChooser(sendIntent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return startSafe(chooser)
    }

    fun copyToClipboard(label: String, text: String) {
        val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        clipboard.setPrimaryClip(ClipData.newPlainText(label, text))
    }

    fun shareCodeFile(fileName: String, content: String): Boolean {
        return try {
            val dir = File(context.cacheDir, "shared_code").apply { mkdirs() }
            val safeName = fileName.replace(Regex("[^a-zA-Z0-9._-]"), "_")
            val file = File(dir, safeName)
            file.writeText(content)
            val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_SUBJECT, safeName)
                putExtra(Intent.EXTRA_STREAM, uri)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            val chooser = Intent.createChooser(intent, "Share $safeName").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            startSafe(chooser)
        } catch (_: Exception) {
            shareText(fileName, content)
        }
    }

    fun shareAndroidProjectZip(projectName: String, codeContent: String, githubUser: String): Boolean {
        return try {
            val dir = File(context.cacheDir, "shared_code").apply { mkdirs() }
            val safeName = projectName.replace(Regex("[^a-zA-Z0-9_-]"), "_").ifBlank { "McGeneratedApp" }
            val zipFile = File(dir, "${safeName}_android_project.zip")

            val readme = buildString {
                appendLine("# $safeName")
                appendLine("Generated by MC Personal AI Assistant")
                if (githubUser.isNotBlank()) {
                    appendLine("GitHub Target: https://github.com/$githubUser/$safeName")
                }
                appendLine()
                appendLine("## Build APK & Install")
                appendLine("```bash")
                appendLine("git init && git add . && git commit -m \"Initial commit from MC Assistant\"")
                appendLine("./gradlew assembleDebug")
                appendLine("# Output APK: app/build/outputs/apk/debug/app-debug.apk")
                appendLine("```")
            }

            val buildGradle = """
                plugins {
                    id("com.android.application")
                    id("org.jetbrains.kotlin.android")
                    id("org.jetbrains.kotlin.plugin.compose")
                }
                android {
                    namespace = "com.mc.generated"
                    compileSdk = 35
                    defaultConfig {
                        applicationId = "com.mc.generated.${safeName.lowercase()}"
                        minSdk = 24
                        targetSdk = 35
                        versionCode = 1
                        versionName = "1.0"
                    }
                    buildFeatures { compose = true }
                }
            """.trimIndent()

            val githubWorkflow = """
                name: Build Android APK
                on: [push, workflow_dispatch]
                jobs:
                  build:
                    runs-on: ubuntu-latest
                    steps:
                      - uses: actions/checkout@v4
                      - uses: actions/setup-java@v4
                        with:
                          distribution: 'temurin'
                          java-version: '17'
                      - run: ./gradlew assembleDebug
                      - uses: actions/upload-artifact@v4
                        with:
                          name: app-debug-apk
                          path: app/build/outputs/apk/debug/app-debug.apk
            """.trimIndent()

            ZipOutputStream(FileOutputStream(zipFile)).use { zos ->
                fun addEntry(path: String, text: String) {
                    zos.putNextEntry(ZipEntry(path))
                    zos.write(text.toByteArray(Charsets.UTF_8))
                    zos.closeEntry()
                }
                addEntry("README.md", readme)
                addEntry("app/build.gradle.kts", buildGradle)
                addEntry("app/src/main/java/com/mc/generated/MainActivity.kt", codeContent)
                addEntry(".github/workflows/build_apk.yml", githubWorkflow)
            }

            val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", zipFile)
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "application/zip"
                putExtra(Intent.EXTRA_SUBJECT, "$safeName Android Project Bundle")
                putExtra(Intent.EXTRA_STREAM, uri)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            val chooser = Intent.createChooser(intent, "Export $safeName Project (.zip)").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            startSafe(chooser)
        } catch (_: Exception) {
            shareText("$projectName Code", codeContent)
        }
    }

    fun openUrl(url: String): Boolean {
        val intent = Intent(Intent.ACTION_VIEW, Uri.parse(url)).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return startSafe(intent)
    }

    fun toggleFlashlight(enable: Boolean): Boolean {
        return try {
            val camManager = context.getSystemService(Context.CAMERA_SERVICE) as CameraManager
            val cameraId = camManager.cameraIdList.firstOrNull() ?: return false
            camManager.setTorchMode(cameraId, enable)
            true
        } catch (_: Exception) {
            false
        }
    }

    fun openSystemPanel(panel: SystemPanelType): Boolean {
        val intent = when (panel) {
            SystemPanelType.WIFI -> {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                    Intent(Settings.Panel.ACTION_INTERNET_CONNECTIVITY)
                } else {
                    Intent(Settings.ACTION_WIFI_SETTINGS)
                }
            }
            SystemPanelType.BLUETOOTH -> Intent(Settings.ACTION_BLUETOOTH_SETTINGS)
            SystemPanelType.VOLUME -> {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                    Intent(Settings.Panel.ACTION_VOLUME)
                } else {
                    Intent(Settings.ACTION_SOUND_SETTINGS)
                }
            }
            SystemPanelType.DISPLAY -> Intent(Settings.ACTION_DISPLAY_SETTINGS)
            SystemPanelType.ACCESSIBILITY -> Intent(Settings.ACTION_ACCESSIBILITY_SETTINGS)
            SystemPanelType.NOTIFICATION_ACCESS -> Intent(Settings.ACTION_NOTIFICATION_LISTENER_SETTINGS)
            SystemPanelType.APP_SETTINGS -> Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS).apply {
                data = Uri.parse("package:${context.packageName}")
            }
        }.apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return startSafe(intent)
    }

    private fun startSafe(intent: Intent): Boolean {
        return try {
            context.startActivity(intent)
            true
        } catch (_: Exception) {
            false
        }
    }
}
